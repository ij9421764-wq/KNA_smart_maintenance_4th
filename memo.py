# NumPy를 배우는 이유 ->  숫자 묶음을 빠르게 계산하는 데이터 분석의 출발점
# NumPy는 모든 데이터 분석 도구의 기초 -> Pandas, Matplotlib도 NumPy 기반
# 리스트는 숫자에 곱셈하면 계산이 아니라 반복 —> 배열은 묶음 전체에 한 줄로 적용
# 리스트 자체가 느린 것이 아니라 값을 하나씩 도는 반복문이 느린것 —> 배열도 반복문으로 하나씩 돌면 이 이점이 사라짐
# 배열은 같은 자료형의 값만 담음 -> 빠름
# 배열은 같은 자료형만 담으므로 더 넓은 쪽으로 자동 통일 -> 하나라도 실수면 실수 배열이 됨
# np.arange -> 시작부터 끝 직전까지 일정 간격으로 값 생성
# np.linspace -> 시작과 끝 사이를 같은 간격의 값 여러 개로 채우기
# 배열은 모양에 따라 1차원과 2차원으로 나뉨
# 1차원 -> 방향이 하나
# 실무에서는 2차원 많이 사용 -> (1000, 20) -> 1000개 시점, 20개 센서
# 데이터를 불러온 직후 dtype 확인이 계산 오류를 막아줌 ->  print(a.dtype)
# astype으로 자료형 바꾸기 : 실수 → 정수는 소수점 버림(a.astype(int)), 원본은 그대로, 새 배열이 생김 -> 결과를 새 이름에 담기
# print(a.reshape(-1, 2)) -> 모양만 바꾸기, -1은 NumPy가 나머지 크기를 자동 계산, -1은 행과 열 중 한 곳에만 사용 가능, 원본 변경 X(변수에 받아서 사용)
# print(b.flatten()) -> 표 모양을 한 줄로 펴기, 원본 변경 X(변수에 받아서 사용
