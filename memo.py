import numpy as np

temp_list = [1, 2, 3]

# [1, 2, 3, 1, 2, 3]
print(temp_list * 2)

# [2 4 6]
# list와 다르게 콤마가 없음(공백으로 값 구분)
numpy_array = np.array(temp_list)
print(numpy_array * 2)

#######################################################

print(np.arange(5))
# 출력: [0 1 2 3 4]
print(np.arange(0, 10, 2))
# 출력: [0 2 4 6 8]

# 마지막 인자 -> 값의 개수
# 값 5개면 구간은 4개
# 끝 값인 1이 포함됨
print(np.linspace(0, 1, 5))
# 출력: [0. 0.25 0.5 0.75 1. ]

#######################################################

# 결과를 담을 빈 그릇을 준비할 때
print(np.zeros(3))
# 출력: [0. 0. 0.]

# 비율이나 가중치 출발점으로
print(np.ones(3))
# 출력: [1. 1. 1.]

# 기준값을 설정할 때
print(np.full(3, 7))
# 출력: [7 7 7]

